# Regenerate src/lib/deck/countyCodes.data.ts from the research files: python3 -I scripts/deck-codes/build.py
# Research JSON (one file per region) → src/lib/deck/countyCodes.data.ts. Every value typed and range-checked;
# anything that does not pass is dropped to null (and said in the county's note).
import json, glob, re, sys, os
SP = os.path.join(os.path.dirname(os.path.abspath(__file__)), "research")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "lib", "deck", "countyCodes.data.ts")
SDC = {"A", "B", "C", "D0", "D1", "D2", "E"}
def num(v, lo, hi):
    if isinstance(v, bool) or v is None: return None
    if isinstance(v, (int, float)) and lo <= v <= hi: return int(v) if float(v).is_integer() else round(float(v), 1)
    return None
def txt(v, n):
    if not isinstance(v, str): return None
    v = re.sub(r"\s+", " ", v).strip()
    return v[:n] if v else None
rows, regions, dropped = [], [], []
for f in sorted(glob.glob(os.path.join(SP, "*.json"))):
    try: d = json.load(open(f))
    except Exception as e: print("unreadable", f, e); continue
    # Only the merged region files: a helper's partial file (no "region") repeats a region's counties.
    if "counties" not in d or not d.get("region"): continue
    regions.append(d["region"])
    for c in d["counties"]:
        st = (c.get("state") or "").strip().upper()
        name = txt(c.get("county"), 60)
        if not re.fullmatch(r"[A-Z]{2}", st) or not name: dropped.append(c.get("county")); continue
        sdc = (c.get("seismic_sdc") or "")
        sdc = sdc.strip().upper().replace(" ", "") if isinstance(sdc, str) else ""
        note = txt(c.get("note"), 400)
        if sdc and sdc not in SDC:
            note = ((note + " ") if note else "") + f"Seismic as published: {sdc}."
            sdc = None
        srcs = []
        for s in (c.get("sources") or [])[:3]:
            if isinstance(s, dict) and isinstance(s.get("url"), str) and s["url"].startswith("http"):
                srcs.append({"title": txt(s.get("title"), 120) or s["url"][:120], "url": s["url"][:400]})
        conf = c.get("confidence") if c.get("confidence") in ("high", "medium", "low") else "low"
        # Read only from archived copies (the county's site refused automated reads): kept, but at low confidence and said so.
        if st == "WA" and name.startswith("Pierce"):
            conf = "low"
            note = ((note + " ") if note else "") + "These figures were read from archived copies of the county's PDFs — confirm them with Pierce County."
        rows.append({
            "state": st, "county": name, "fips": txt(c.get("fips"), 5) if re.fullmatch(r"\d{5}", str(c.get("fips") or "")) else None,
            "jurisdiction": txt(c.get("jurisdiction"), 200) or "the county's building department",
            "edition": txt(c.get("edition"), 200),
            "frostIn": num(c.get("frost_depth_in"), 0, 120), "groundSnowPsf": num(c.get("ground_snow_psf"), 0, 400),
            "windMph": num(c.get("wind_mph"), 70, 220), "windBasis": txt(c.get("wind_basis"), 80),
            "sdc": sdc or None, "weathering": txt(c.get("weathering"), 40), "termite": txt(c.get("termite"), 40),
            "deckNotes": [x for x in (txt(n, 240) for n in (c.get("deck_notes") or [])[:6]) if x],
            "note": note, "sources": srcs, "confidence": conf,
        })
seen, uniq = set(), []
for r in rows:
    k = (r["state"], re.sub(r"[^a-z0-9]", "", r["county"].lower()))
    if k in seen: continue
    seen.add(k); uniq.append(r)
rows = sorted(uniq, key=lambda r: (r["state"], r["county"]))
head = f"""// THE COUNTIES ON FILE — generated by the 2026-10-20 research (regions: {', '.join(regions)}).
// Each figure was read from the jurisdiction's own page or the adopted code, with its source; null where none
// was published. Regenerate from the research JSON, never edit a figure by hand without a source.
import type {{ DeckCountyCode }} from "./countyCodes";

export const COUNTY_RESEARCHED_ON = "2026-10-20";

export const COUNTY_CODES: DeckCountyCode[] = """
with open(OUT, "w") as fh:
    fh.write(head + json.dumps(rows, indent=1, ensure_ascii=False) + ";\n")
print(f"{len(rows)} counties from {len(regions)} regions written; dropped {len(dropped)}")
nulls = {k: sum(1 for r in rows if r[k] is None) for k in ("frostIn", "groundSnowPsf", "windMph", "sdc")}
print("nulls:", nulls)
