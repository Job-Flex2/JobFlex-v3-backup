// Writes src/lib/seo/city-indices.data.ts from the research table in
// docs/pricing-sources-cities.md (2026-10-26).
//
// The city cost index (lib/estimate/location-index-data) keeps only the
// composite factor. The table it came from also prints, per city, the labor
// index (the metro's BLS construction wage over the U.S. mean, times the
// county adjustment), the material index (Craftsman ZIP3) and the published
// indices it was checked against. The cost guides (/cost) explain a city's
// price with those, so they are read here into a plain data file — a deployed
// page cannot read the docs folder. Run again whenever the table changes:
//
//   npx tsx scripts/seo-city-data.ts
//
// A row whose note does not carry "L x.xx" and "M x.xx" (New York and
// Manhattan, set by rule) is written without them, and the page leaves the
// labor-and-materials sentence out.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CITY_COST_INDEX } from "../src/lib/estimate/location-index-data";

const root = join(__dirname, "..");
const doc = readFileSync(join(root, "docs/pricing-sources-cities.md"), "utf8");
const start = doc.indexOf("## City factors");
const end = doc.indexOf("## State index corrections");
if (start < 0 || end < 0) throw new Error("The city table's headings moved — update scripts/seo-city-data.ts.");

const num = (re: RegExp, text: string): number | undefined => {
  const m = text.match(re);
  return m ? Number(m[1]) : undefined;
};

type Row = { city: string; state: string; factor: number; labor?: number; laborMetro?: number; county?: number; material?: number; rsmeans?: number; hud?: number; craftsman?: number };
const rows: Row[] = [];
for (const line of doc.slice(start, end).split("\n")) {
  if (!line.startsWith("| ") || line.startsWith("| City") || line.startsWith("|---")) continue;
  const cells = line.split("|").map((c) => c.trim());
  const [, city, state, factor, , note] = cells;
  const n = note ?? "";
  const labor = num(/\bL (\d\.\d+)/, n);
  const material = num(/\bM (\d\.\d+)/, n);
  rows.push({
    city,
    state,
    factor: Number(factor),
    ...(labor != null && material != null ? { labor, material } : {}),
    ...(labor != null && material != null ? { laborMetro: num(/metro (\d\.\d+) x county/, n), county: num(/x county (\d\.\d+)/, n) } : {}),
    // The checks, on their own bases. DoD is left out: its Alaska and Hawaii
    // values are military-logistics factors the table calls not comparable.
    rsmeans: num(/RSMeans res\. (\d\.\d+)/, n),
    hud: num(/\bHUD (\d\.\d+)/, n),
    craftsman: num(/\bCraftsman (\d\.\d+)/, n),
  });
}

// The table and the index must be the same 306 rows with the same factors.
const key = (c: string, s: string) => `${c}|${s}`;
const byKey = new Map(rows.map((r) => [key(r.city, r.state), r]));
for (const c of CITY_COST_INDEX) {
  const r = byKey.get(key(c.city, c.state));
  if (!r) throw new Error(`${c.city}, ${c.state} is in location-index-data but not in the docs table.`);
  if (Math.abs(r.factor - c.factor) > 0.001) throw new Error(`${c.city}, ${c.state}: docs ${r.factor} vs index ${c.factor}.`);
}
if (rows.length !== CITY_COST_INDEX.length) throw new Error(`docs has ${rows.length} rows, the index ${CITY_COST_INDEX.length}.`);

const clean = (r: Row) => {
  const out: Record<string, string | number> = { city: r.city, state: r.state };
  for (const k of ["labor", "laborMetro", "county", "material", "rsmeans", "hud", "craftsman"] as const) if (r[k] != null) out[k] = r[k] as number;
  return out;
};

const literal = (r: Row) =>
  JSON.stringify(clean(r))
    .replace(/"(\w+)":/g, "$1: ")
    .replace(/,(?=\w)/g, ", ")
    .replace(/^\{/, "{ ")
    .replace(/\}$/, " }");
const body = rows.map((r) => `  ${literal(r)},`).join("\n");
const file = `// GENERATED by scripts/seo-city-data.ts from docs/pricing-sources-cities.md — do not edit by hand.
// Per city: labor = BLS OEWS May 2025 construction wage for the metro over the
// U.S. mean, times the county adjustment (laborMetro x county where the table
// prints them); material = Craftsman ZIP3 material factor; rsmeans / hud /
// craftsman = the published indices the composite was checked against, each
// on its own base. The composite factor itself stays in
// lib/estimate/location-index-data. Plain data.

export type CityIndices = {
  city: string;
  state: string;
  labor?: number;
  laborMetro?: number;
  county?: number;
  material?: number;
  rsmeans?: number;
  hud?: number;
  craftsman?: number;
};

export const CITY_INDICES: CityIndices[] = [
${body}
];
`;
writeFileSync(join(root, "src/lib/seo/city-indices.data.ts"), file);
console.log(`wrote ${rows.length} rows (${rows.filter((r) => r.labor != null).length} with labor and material)`);
